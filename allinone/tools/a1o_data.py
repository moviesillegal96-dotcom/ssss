#!/usr/bin/env python3
"""Builds the A1O app's data file from three sources.

    python3 tools/a1o_data.py All-in-One.xlsx a1o-data.js a1o-backup.json app/data.js

- The workbook becomes the All in 1 library, in full (via xlsx2data.py).
- a1o-data.js (the data file inside the A1O app) gives the sections A1O added that the workbook does not have:
  the "Tujuan" sheet, the "Catatan" sheet and the study plan list. Its reminders and one-time to-dos come along too.
- The backup (exported from the app: Lainnya -> Simpan backup) is the app's starting state: to-dos, deadlines,
  lists, ticks, money, reminders and notes. A phone that already has data keeps its own.

Afterwards every place the backup points to (lists, routines, notes, picks) is checked against the library.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from xlsx2data import convert  # noqa: E402


def read_a1o(path):
    """The main object and any extra `window.AIO_DATA.<key> = …;` assignments of a data.js file."""
    src = open(path, encoding='utf-8').read()
    dec = json.JSONDecoder()
    start = src.index('window.AIO_DATA = ') + len('window.AIO_DATA = ')
    data, _ = dec.raw_decode(src[start:])
    for m in re.finditer(r'window\.AIO_DATA\.(\w+) = ', src):
        data[m.group(1)], _ = dec.raw_decode(src[m.end():])
    return data


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    xlsx, a1o_path, backup_path, out_path = sys.argv[1:]
    lib = convert(xlsx)
    a1o = read_a1o(a1o_path)
    backup = json.load(open(backup_path, encoding='utf-8'))
    state = backup.get('state', backup)

    a1o_sheets = {s['id']: s for s in a1o['sheets']}
    a1o_sections = {sec['id']: sec for s in a1o['sheets'] for sec in s['sections']}
    sheets = []
    if 'tujuan' in a1o_sheets:
        sheets.append(a1o_sheets['tujuan'])
    sheets += lib['sheets']
    if 'catatan' in a1o_sheets:
        sheets.append(a1o_sheets['catatan'])

    # Sections the workbook also has keep the workbook's content; lists A1O added to them go on top.
    lib_sections = {sec['id']: sec for s in sheets for sec in s['sections']}
    for sid, extra in a1o_sections.items():
        if sid in lib_sections and lib_sections[sid] is not extra:
            own = {b.get('id') for b in lib_sections[sid]['blocks'] if b.get('id')}
            add = [b for b in extra['blocks'] if b.get('t') == 'grid' and b.get('id') and b['id'] not in own]
            if add:
                lib_sections[sid]['blocks'][:0] = [{'t': 'h', 'l': 3, 'x': extra['title']}] + add

    seeds = lib['seeds']
    seeds['reminders'] = a1o.get('seeds', {}).get('reminders') or seeds.get('reminders', [])
    data = {
        'source': os.path.basename(xlsx) + ' + ' + os.path.basename(backup_path),
        'owner': state.get('settings', {}).get('name') or a1o.get('owner') or lib.get('owner', ''),
        'sheets': sheets, 'seeds': seeds, 'backup': state,
    }
    if a1o.get('addTodos'):
        data['addTodos'] = a1o['addTodos']

    # Everything the backup points to should still exist.
    sections = {sec['id'] for s in sheets for sec in s['sections']}
    blocks = {b['id'] for s in sheets for sec in s['sections'] for b in sec['blocks'] if b.get('id')}
    missing = []
    for t in state.get('tasks', []):
        if t.get('ref') and t['ref'] not in blocks:
            missing.append('routine "%s" -> %s' % (t.get('title', '')[:40], t['ref']))
    for k, v in state.get('lists', {}).items():
        if k not in blocks:
            missing.append('edited list %s (%d items)' % (k, len(v)))
    for wk in state.get('picks', {}).values():
        missing += ['study picks ' + k for k in wk if k not in blocks]
    for p in state.get('pasted', []):
        if p.get('sec') not in sections:
            missing.append('pasted notes -> ' + str(p.get('sec')))
    for k in state.get('notes', {}):
        if k not in sections:
            missing.append('notes -> ' + k)

    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('/* A1O — All in 1 from %s; starting data from %s. Generated by tools/a1o_data.py. */\n'
                % (os.path.basename(xlsx), os.path.basename(backup_path)))
        f.write('window.AIO_DATA = ')
        json.dump(data, f, ensure_ascii=False, separators=(',', ':'))
        f.write(';\n')
    n_sec = sum(len(s['sections']) for s in sheets)
    print('%d sheets, %d sections; backup: %d to-dos, %d routines, %d deadlines -> %s'
          % (len(sheets), n_sec, len(state.get('todos', [])), len(state.get('tasks', [])), len(state.get('deadlines', [])), out_path))
    for m in missing:
        print('  not in the library: ' + m)


if __name__ == '__main__':
    main()
